@pytest.fixture
def keypoints_payload() -> dict:
    """A hand-written keypoints.json: 13 frames of an arm swinging and back.

    Written out rather than inferred so the picker's tests do not depend on a
    model download - and so the expected answer is obvious by inspection: the
    arm is furthest from rest at frame 6.
    """
    names = ["nose", "neck", "right_shoulder", "right_elbow", "right_wrist",
             "left_shoulder", "left_elbow", "left_wrist", "right_hip",
             "right_knee", "right_ankle", "left_hip", "left_knee", "left_ankle",
             "right_eye", "left_eye", "right_ear", "left_ear"]
    frames = []
    swing = [0, 0, 0, 10, 25, 45, 60, 45, 25, 10, 0, 0, 0]
    for index, reach in enumerate(swing):
        kp = [
            [180, 60], [180, 110], [188, 118], [196, 160], [200, 205],
            [172, 118], [164, 160], [160, 205], [186, 210], [190, 280],
            [192, 350], [174, 210], [170, 280], [168, 350],
            [186, 54], [176, 54], [188, 62], [172, 62],
        ]
        # only the swinging arm moves, and it moves a long way
        kp[3] = [196 + reach, 160 - reach // 2]
        kp[4] = [200 + reach * 2, 205 - reach]
        frames.append({"index": index, "file": f"{index + 1:04d}.png",
                       "keypoints": kp, "scores": [0.9] * 18,
                       "person": {"score": 0.9}})
    return {"schema": "anim.keypoints/1", "rig": "openpose18", "names": names,
            "model": "canned", "mode": "canned", "kpt_thr": 0.4,
            "source_size": [360, 420], "frames": frames}


@pytest.fixture
def posed_job(work_dir: Path, keypoints_payload: dict):
    """A job that already has frames, keypoints and skeletons - as if `pose` ran.

    Six stages downstream of `pose` need this exact state, and building it by
    running inference in each would need the ONNX weights.
    """
    from anim.job import Job, new_manifest
    from anim.stages.pose import render_skeletons

    job = Job.open("knight_strike", work_dir)
    job.frames_dir.mkdir(parents=True, exist_ok=True)
    for index, frame in enumerate(synthetic.frame_series(13, (360, 420))):
        frame.save(job.frames_dir / f"{index + 1:04d}.png")
    job.write_manifest(new_manifest(
        clip="knight_strike.mp4", clip_sha256="a" * 64, fps=12, frames=13,
        action="strike", slug="knight", frame_size=[360, 420], crop=None,
        source_fps=24.0, created="2026-09-13T00:00:00+00:00"))
    job.pose_dir.mkdir(parents=True, exist_ok=True)
    (job.keypoints_path).write_text(json.dumps(keypoints_payload), encoding="utf-8")
    render_skeletons(keypoints_payload, job.pose_dir)
    return job


