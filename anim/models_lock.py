"""Read gpu/models.lock - repo, revision, file, size, sha256, licence per weight.

A generated frame's sidecar has to name the exact weights it passed through, and
those hashes must come from the lockfile rather than being typed into the
sidecar writer: models.lock is regenerated by gpu/relock_models.py against the
Hugging Face API, and a second hand-maintained copy of the same hash would drift
the first time a model is re-pinned.

Format (tab separated, # comments):
    repo_id  revision  repo_file  dest_subdir  dest_filename  size  sha256  license
"""

from __future__ import annotations

from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Any

from anim import config


@dataclass(frozen=True)
class LockedModel:
    repo: str
    revision: str
    repo_file: str
    subdir: str
    file: str
    size: int
    sha256: str
    license: str

    def as_sidecar_entry(self) -> dict[str, Any]:
        """The shape the audit's CREDITS generator reads (repo + file + licence)."""
        return {"repo": self.repo, "file": self.file,
                "sha256": self.sha256, "license": self.license,
                "revision": self.revision}

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


def load(path: Path | None = None) -> list[LockedModel]:
    """Every row in the lockfile. Missing file -> empty list, not an error.

    Empty rather than raising because `render` against a fake server and `post`
    on a fixture strip are both legitimate without a GPU basedir; the stage that
    genuinely needs the hashes (`publish`) is the one that complains.
    """
    path = Path(path) if path is not None else config.MODELS_LOCK
    if not path.exists():
        return []
    models: list[LockedModel] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 8:
            continue
        repo, revision, repo_file, subdir, filename, size, sha, licence = parts[:8]
        models.append(LockedModel(repo.strip(), revision.strip(), repo_file.strip(),
                                  subdir.strip(), filename.strip(),
                                  int(size.strip() or 0), sha.strip(),
                                  licence.strip()))
    return models


def for_workflow(workflow: dict[str, Any],
                 path: Path | None = None) -> list[LockedModel]:
    """The locked weights a workflow actually names.

    Scans every node's string inputs for a locked `dest_filename`. That is
    deliberately dumb: the alternative is a per-node-class table of which input
    key holds a model name, which would go stale the moment a workflow gains a
    node. A filename is a filename wherever it appears.
    """
    models = load(path)
    wanted: list[LockedModel] = []
    blob = _string_inputs(workflow)
    for model in models:
        if model.file in blob and model not in wanted:
            wanted.append(model)
    return wanted


def _string_inputs(workflow: dict[str, Any]) -> set[str]:
    values: set[str] = set()
    for node in workflow.values():
        for value in (node.get("inputs") or {}).values():
            if isinstance(value, str):
                values.add(value)
    return values
